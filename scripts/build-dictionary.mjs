function rarityFor(word, rank, total) {
  const upper = word.toUpperCase();
  const hasRare = [...upper].some((c) => RARE_LETTERS.has(c));
  const len = word.length;
  if (rank < total * 0.35 && len <= 5 && !hasRare) return "common";
  if (rank < total * 0.7 && len <= 7) return hasRare ? "uncommon" : "common";
  if (hasRare || len >= 9) return len >= 10 || (hasRare && len >= 7) ? "epic" : "rare";
  return "uncommon";
}

function fallbackDefinition(word, rarity) {
  const tips = {
    common: "A familiar English word.",
    uncommon: "A less common English word.",
    rare: "An uncommon English word — nice find!",
    epic: "A rare or lengthy English word — excellent!",
  };
  return tips[rarity] ?? "A valid English word.";
}

function isBlocked(word) {
  const w = word.toLowerCase();
  if (BLOCKLIST.has(w)) return true;
  for (const bad of BLOCKLIST) {
    if (bad.length >= 4 && w.includes(bad)) return true;
  }
  return false;
}

function loadWordLines(filePath) {
  if (!fs.existsSync(filePath)) return [];
  return fs
    .readFileSync(filePath, "utf8")
    .split(/\r?\n/)
    .map((l) => l.trim().toLowerCase())
    .filter(Boolean);
}

function acceptWord(w, seen) {
  if (w.length < MIN_LEN || w.length > MAX_LEN) return false;
  if (!/^[a-z]+$/.test(w)) return false;
  if (isBlocked(w)) return false;
  if (seen.has(w)) return false;
  return true;
}

