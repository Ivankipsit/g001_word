// Frequency-leaning list first, then large alpha fill (longer / rarer words).
const primary = loadWordLines(path.join(__dirname, "raw-words.txt"));
const secondary = loadWordLines(LARGE_LIST_PATH);

const seen = new Set();
const filtered = [];

for (const w of primary) {
  if (!acceptWord(w, seen)) continue;
  seen.add(w);
  filtered.push(w);
  if (filtered.length >= MAX_WORDS) break;
}

if (filtered.length < MAX_WORDS) {
  // Prefer longer secondary words to expand beyond the short starter list.
  const longFirst = [...secondary].sort((a, b) => b.length - a.length || a.localeCompare(b));
  for (const w of longFirst) {
    if (!acceptWord(w, seen)) continue;
    seen.add(w);
    filtered.push(w);
    if (filtered.length >= MAX_WORDS) break;
  }
}

// Ensure forge-themed / gameplay words exist
const extras = [
  "forge", "anagram", "lexicon", "idle", "bonus", "chain", "tile", "vowel",
  "consonant", "puzzle", "quest", "craft", "spark", "bloom", "glow", "vault",
  "keystone",
];
for (const w of extras) {
  if (!seen.has(w) && acceptWord(w, seen)) {
    filtered.push(w);
    seen.add(w);
  }
}

const entries = filtered.map((word, i) => {
  const rarity = rarityFor(word, i, filtered.length);
  const def = DEFS[word] ?? fallbackDefinition(word, rarity);
  return [word, def, rarity === "common" ? 0 : rarity === "uncommon" ? 1 : rarity === "rare" ? 2 : 3];
});

