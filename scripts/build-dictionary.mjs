const LARGE_LIST_URL =
  "https://raw.githubusercontent.com/dwyl/english-words/master/words_alpha.txt";
const LARGE_LIST_PATH = path.join(__dirname, "raw-words-large.txt");

async function ensureLargeList() {
  if (fs.existsSync(LARGE_LIST_PATH)) {
    const lines = fs.readFileSync(LARGE_LIST_PATH, "utf8").split(/\r?\n/).length;
    if (lines > 50_000) return;
  }
  console.log("Downloading large word list…");
  try {
    const res = await fetch(LARGE_LIST_URL);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const text = await res.text();
    fs.writeFileSync(LARGE_LIST_PATH, text);
    console.log(`Cached ${LARGE_LIST_PATH}`);
  } catch (err) {
    console.warn("Could not download large list; using raw-words.txt only.", err.message);
  }
}

